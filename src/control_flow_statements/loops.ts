// for loop
/*
      // syntax
      for (initialization; condition; expression) {

      }
      
      // for loop without any statements.
      for(;;) {

      }
      
      // for loop without body
      for (initialization; condition; expression); 

      // label
      labelName: for (initialization; condition; expression) {
        if(condition) {
          break labelName;
        } else {
          continue labelName;
        }
      }
 */
// infinite for-loop
for (; !false;) {}

// while
/*
      while (condition) {

      }
*/

while (2 > 3) {
  // do something
}

// infinite loop
while (!false) {}

// do-while
/*
     do {
      // do something. 
     } while();
*/

do {} while (true);

/*
 *
 *    break     : use to terminate the loop
 *    continue  : use to continue to the next iteration.
 * */
